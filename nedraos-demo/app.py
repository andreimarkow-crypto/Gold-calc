choice=st.selectbox("Выберите услугу",range(len(SERVICES)),format_func=lambda i:f"{SERVICES[i].code} · {SERVICES[i].name}")
s=SERVICES[choice]
a,b,c=st.columns(3)
a.metric("Услуга",s.code)
b.metric("Стоимость (ориентир)",s.price)
c.metric("Срок изготовления пакета",s.period)
st.subheader("Карточка учебного заказа")
col1,col2=st.columns(2)
with col1:
    st.text_input("Клиент",value="ООО «ГеоДемо» (вымышленная организация)",disabled=True)
with col2:
    st.text_input("Лицензия",value="ДЕМО 00001 БР (вымышленный номер)",disabled=True)
st.subheader("Комплект исходных документов")
st.caption("Отметки имитируют получение и проверку документов — загрузка реальных файлов отключена.")
def k(name):
    return f"{s.code}:{name}"
confirmed=[]
for req in s.requirements:
    state=st.selectbox(req,["Нет документа","Получен — не проверен","Проверен и принят","Есть подтверждённая версия в архиве"],key=k(req))
    if state in ["Проверен и принят","Есть подтверждённая версия в архиве"]:
        confirmed.append(req)
ready=len(confirmed)==len(s.requirements)
st.progress(len(confirmed)/len(s.requirements),text=f"Подтверждено {len(confirmed)} из {len(s.requirements)} обязательных входных позиций")
st.subheader("Производственные контрольные точки")
if not ready:
    st.error("⛔ Производство заблокировано: обязательный комплект не подтверждён.")
    st.markdown("**Требуется:** "+"; ".join(r for r in s.requirements if r not in confirmed))
else:
    st.success("✅ Входной комплект по демонстрационным отметкам принят. Это не означает реальную проверку документов.")
if "review" not in st.session_state:
    st.session_state.review=False
if "quality" not in st.session_state:
    st.session_state.quality=False
st.checkbox("Профильная экспертная проверка завершена (демо)",key="review",disabled=not ready)
st.checkbox("Контроль качества завершён (демо)",key="quality",disabled=(not ready or not st.session_state.review))
if ready and st.session_state.review and st.session_state.quality:
    st.success(f"Демонстрационный маршрут завершён. Предполагаемый результат: {s.outcome}.")
else:
    st.warning("Выдача результата заблокирована до выполнения всех контрольных точек.")
with st.expander("Как это работает в полной системе"):
    st.write("Полная НедраOS должна связывать исходные документы, версии лицензий, доказательства получения, проверку эксперта и согласованный результат. Эта версия демонстрирует интерфейс и правила; не является сервисом юридической или геологической проверки.")
st.divider()
